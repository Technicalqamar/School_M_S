import { useState, useEffect, useMemo } from 'react';
import { useOutletContext } from 'react-router-dom';
import {
  IdentificationIcon,
  PrinterIcon,
  ArrowDownTrayIcon,
  ChevronDownIcon,
} from '@heroicons/react/24/outline';
import toast from 'react-hot-toast';
import Alert from '../../common/Alert/Alert';
import Spinner from '../../common/Spinner/Spinner';
import examService from '../../../services/exam/exam.service';
import admitCardService from '../../../services/admitCard/admitCard.service';
import { useSchoolConfig } from '../../../contexts/SchoolConfigContext';
import {
  buildAdmitCardPrintableHtml,
  printHtml,
  downloadAdmitCardPdf,
} from '../../examManagement/shared/admitCardHtml';
import { EmptyState } from '../StudentProfile/shared';

// Single Student Management → "Admit Card".
//
// The admit card is generated by the SAME existing generator the admin
// Examination → Admit Card page uses (`shared/admitCardHtml.js`, fed by the
// existing `GET /api/v1/admit-cards` individual mode). The server owns every
// eligibility rule: the exam must belong to the student's class and academic
// year, a schedule must actually be published for that exam/class, and the
// student must be enrolled for the selected year. When those rules fail the
// page shows the server's explanation instead of a blank card.
const StudentAdmitCard = () => {
  const { student } = useOutletContext();
  const { schoolInfo, academic } = useSchoolConfig();

  const className = student?.class || '';
  const academicYear = student?.academicYear || academic?.currentYear || '';

  const [exams, setExams] = useState([]);
  const [loadingExams, setLoadingExams] = useState(true);
  const [examId, setExamId] = useState('');
  const [admitCard, setAdmitCard] = useState(null);
  const [loadingCard, setLoadingCard] = useState(true);
  const [error, setError] = useState('');
  const [printing, setPrinting] = useState(false);
  const [exporting, setExporting] = useState(false);

  useEffect(() => {
    if (!academicYear || !className) return undefined;
    let cancelled = false;
    examService
      .getAllExams({ academicYear, limit: 100 })
      .then((response) => {
        if (cancelled) return;
        const list = response?.data?.exams || [];
        const forClass = list.filter((exam) => (exam.classes || []).includes(className));
        setExams(forClass);
        setExamId((current) =>
          current && forClass.some((e) => e._id === current) ? current : forClass[0]?._id || '',
        );
      })
      .catch(() => {
        if (!cancelled) setExams([]);
      })
      .finally(() => {
        if (!cancelled) setLoadingExams(false);
      });
    return () => {
      cancelled = true;
    };
  }, [academicYear, className]);

  useEffect(() => {
    if (!examId || !className || !academicYear || !student?.studentId) return undefined;
    let cancelled = false;
    admitCardService
      .getAdmitCard({
        studentId: student._id || student.studentId,
        className,
        examId,
        academicYear,
      })
      .then((response) => {
        if (cancelled) return;
        const data = response?.data || {};
        setAdmitCard(data.mode === 'individual' ? data.admitCard : null);
        setError('');
      })
      .catch((err) => {
        if (cancelled) return;
        setAdmitCard(null);
        setError(err?.response?.data?.message || 'Could not generate the admit card for this student.');
      })
      .finally(() => {
        if (!cancelled) setLoadingCard(false);
      });
    return () => {
      cancelled = true;
    };
  }, [examId, className, academicYear, student]);

  const printableHtml = useMemo(
    () => (admitCard ? buildAdmitCardPrintableHtml(admitCard, schoolInfo) : ''),
    [admitCard, schoolInfo],
  );

  const handlePrint = () => {
    if (!printableHtml) return;
    setPrinting(true);
    try {
      printHtml(printableHtml);
    } finally {
      setPrinting(false);
    }
  };

  const handleDownloadPdf = async () => {
    if (!printableHtml) return;
    setExporting(true);
    try {
      const filename = `AdmitCard-${admitCard.student?.studentId || 'student'}-${(admitCard.exam?.name || 'exam').replace(/[^a-z0-9]+/gi, '-')}.pdf`;
      await downloadAdmitCardPdf(printableHtml, filename);
      toast.success('Admit card PDF downloaded');
    } catch {
      toast.error('PDF download failed. Try the Print option instead.');
    } finally {
      setExporting(false);
    }
  };

  if (!student) return null;

  if (!className || !academicYear) {
    return (
      <EmptyState
        icon={IdentificationIcon}
        title="Admit card is not available"
        message="This student has no class/academic year recorded, so no admit card can be generated."
      />
    );
  }

  return (
    <div className="space-y-5">
      <div className="flex flex-col sm:flex-row sm:items-end sm:justify-between gap-3">
        <div>
          <h2 className="text-lg font-semibold text-gray-900 dark:text-white flex items-center gap-2">
            <IdentificationIcon className="h-5 w-5 text-blue-600 dark:text-blue-400" />
            Admit Card
          </h2>
          <p className="text-xs text-gray-500 dark:text-gray-400 mt-1">
            {student.fullName} ({student.studentId}) — Class {className} · {academicYear}
          </p>
        </div>
        {exams.length > 0 ? (
          <div className="relative">
            <select
              value={examId}
              onChange={(e) => {
                setExamId(e.target.value);
                setLoadingCard(true);
                setAdmitCard(null);
                setError('');
              }}
              className="appearance-none w-full sm:w-64 px-4 py-2.5 pr-10 rounded-lg border border-gray-300 dark:border-gray-600 bg-white dark:bg-gray-800 text-sm text-gray-700 dark:text-gray-200 focus:outline-none focus:ring-2 focus:ring-blue-500/20 focus:border-blue-500"
            >
              {exams.map((exam) => (
                <option key={exam._id} value={exam._id}>
                  {exam.name} ({exam.type})
                </option>
              ))}
            </select>
            <ChevronDownIcon className="h-4 w-4 text-gray-400 absolute right-3 top-1/2 -translate-y-1/2 pointer-events-none" />
          </div>
        ) : null}
      </div>

      {loadingExams ? (
        <div className="flex justify-center py-10">
          <Spinner />
        </div>
      ) : exams.length === 0 ? (
        <EmptyState
          icon={IdentificationIcon}
          title="No exams for this class"
          message={`No exam has been set up for Class ${className} in ${academicYear} yet.`}
        />
      ) : loadingCard ? (
        <div className="flex justify-center py-10">
          <Spinner />
        </div>
      ) : error ? (
        <Alert type="info" message={error} />
      ) : !admitCard ? (
        <Alert type="info" message="No admit card is available for the selected exam." />
      ) : (
        <>
          <div className="flex items-center gap-2">
            <button
              type="button"
              onClick={handlePrint}
              disabled={printing || !printableHtml}
              className="inline-flex items-center gap-1.5 px-4 py-2 rounded-lg border border-gray-300 dark:border-gray-600 text-sm font-medium text-gray-700 dark:text-gray-200 hover:bg-gray-50 dark:hover:bg-gray-700 transition-all cursor-pointer disabled:opacity-50"
            >
              <PrinterIcon className="h-4 w-4" />
              Print
            </button>
            <button
              type="button"
              onClick={handleDownloadPdf}
              disabled={exporting || !printableHtml}
              className="inline-flex items-center gap-1.5 px-4 py-2 rounded-lg bg-blue-600 text-white text-sm font-medium hover:bg-blue-700 transition-all cursor-pointer disabled:opacity-50"
            >
              <ArrowDownTrayIcon className="h-4 w-4" />
              {exporting ? 'Preparing…' : 'Download PDF'}
            </button>
          </div>

          <div className="rounded-xl border border-gray-200 dark:border-gray-700 bg-white dark:bg-gray-800 overflow-hidden">
            <iframe
              title="Admit Card Preview"
              srcDoc={printableHtml}
              className="w-full"
              style={{ height: '720px', border: 'none' }}
            />
          </div>
        </>
      )}
    </div>
  );
};

export default StudentAdmitCard;
